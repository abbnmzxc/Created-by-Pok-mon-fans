create table if not exists public.leaderboard (
  id bigint generated by default as identity primary key,
  trainer text not null,
  pokemon text not null default 'Pokémon',
  score integer not null default 0,
  survival integer not null default 0,
  created_at timestamptz not null default now()
);

alter table public.leaderboard enable row level security;

drop policy if exists "Anyone can read leaderboard" on public.leaderboard;
create policy "Anyone can read leaderboard"
  on public.leaderboard for select
  to anon, authenticated
  using (true);

drop policy if exists "Anyone can submit leaderboard scores" on public.leaderboard;
create policy "Anyone can submit leaderboard scores"
  on public.leaderboard for insert
  to anon, authenticated
  with check (score >= 0 and survival >= 0 and length(trainer) between 2 and 16);

create index if not exists leaderboard_score_idx
  on public.leaderboard (score desc, survival desc);

-- 開啟即時排行榜事件（若已加入 publication，Supabase 會提示已存在即可忽略）
alter publication supabase_realtime add table public.leaderboard;
